-- Provision the loader role. Set its password separately.
CREATE ROLE pyrogravity_nasa_loader LOGIN
    NOSUPERUSER NOCREATEDB NOCREATEROLE NOREPLICATION NOBYPASSRLS NOINHERIT;

GRANT CONNECT ON DATABASE postgres TO pyrogravity_nasa_loader;
GRANT USAGE ON SCHEMA scientific TO pyrogravity_nasa_loader;

-- Repeated loads read and compare complete versions, including conflict keys.
GRANT SELECT ON TABLE
    scientific.investigations, scientific.datasets, scientific.dataset_columns,
    scientific.records, scientific.measurements
TO pyrogravity_nasa_loader;

GRANT INSERT ON TABLE
    scientific.investigations, scientific.dataset_columns,
    scientific.records, scientific.measurements
TO pyrogravity_nasa_loader;

-- dataset_id is generated by PostgreSQL and read through RETURNING.
GRANT INSERT (
    psi_code, relative_path, sha256, encoding, delimiter, row_count,
    column_count, data_scope, quantitative_criteria, source_observations,
    quality_reference
) ON TABLE scientific.datasets TO pyrogravity_nasa_loader;

CREATE POLICY nasa_loader_select ON scientific.investigations
    FOR SELECT TO pyrogravity_nasa_loader USING (true);
CREATE POLICY nasa_loader_insert ON scientific.investigations
    FOR INSERT TO pyrogravity_nasa_loader WITH CHECK (true);

CREATE POLICY nasa_loader_select ON scientific.datasets
    FOR SELECT TO pyrogravity_nasa_loader USING (true);
CREATE POLICY nasa_loader_insert ON scientific.datasets
    FOR INSERT TO pyrogravity_nasa_loader WITH CHECK (true);

CREATE POLICY nasa_loader_select ON scientific.dataset_columns
    FOR SELECT TO pyrogravity_nasa_loader USING (true);
CREATE POLICY nasa_loader_insert ON scientific.dataset_columns
    FOR INSERT TO pyrogravity_nasa_loader WITH CHECK (true);

CREATE POLICY nasa_loader_select ON scientific.records
    FOR SELECT TO pyrogravity_nasa_loader USING (true);
CREATE POLICY nasa_loader_insert ON scientific.records
    FOR INSERT TO pyrogravity_nasa_loader WITH CHECK (true);

CREATE POLICY nasa_loader_select ON scientific.measurements
    FOR SELECT TO pyrogravity_nasa_loader USING (true);
CREATE POLICY nasa_loader_insert ON scientific.measurements
    FOR INSERT TO pyrogravity_nasa_loader WITH CHECK (true);
